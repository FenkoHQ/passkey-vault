#!/usr/bin/env node
/**
 * Regenerate src/utils/public-suffix-list.ts from the Public Suffix List.
 *
 *   node scripts/update-public-suffix-list.js            # fetch publicsuffix.org
 *   node scripts/update-public-suffix-list.js --from FILE  # use a downloaded copy
 *
 * Both sections are kept, ICANN and PRIVATE, because Chrome checks WebAuthn
 * RP IDs with INCLUDE_PRIVATE_REGISTRIES (components/webauthn/core/browser/
 * webauthn_security_utils.cc): a page on foo.github.io may not claim
 * github.io. Rules are stored in their ASCII (punycode) form, which is what
 * URL hostnames and RP IDs use.
 *
 * The list is written as a trie keyed on labels from the right, one
 * top-level domain per array element so a list update diffs by TLD:
 *
 *   node     := label marker? children?
 *   marker   := "!" (exception rule) | "?" (not a rule, only a path)
 *               no marker: the labels down to here are a rule
 *   children := "(" node ("," node)* ")"
 *
 * e.g. "ck?(*,www!)" holds the rules *.ck and !www.ck. The runtime side is
 * createSuffixMatcher() in src/utils/domain.ts.
 */

'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const url = require('url');

const SOURCE_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUTPUT = path.join(__dirname, '..', 'src', 'utils', 'public-suffix-list.ts');
const LABEL = /^(\*|[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)$/;

/** The rules of a public_suffix_list.dat, in ASCII, with the section each is in. */
function parseList(text) {
  const rules = [];
  let section = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.includes('===BEGIN ICANN DOMAINS===')) section = 'icann';
    else if (line.includes('===BEGIN PRIVATE DOMAINS===')) section = 'private';
    else if (line.includes('===END ')) section = null;
    if (line === '' || line.startsWith('//')) continue;
    if (!section) throw new Error(`Rule outside a section: ${line}`);

    // A rule is the first whitespace-separated token on its line.
    let rule = line.split(/\s/)[0];
    const exception = rule.startsWith('!');
    if (exception) rule = rule.slice(1);
    const wildcard = rule.startsWith('*.');
    // Converted as a whole name: a lone label such as "0" would be read as
    // an IPv4 address.
    const ascii = url.domainToASCII(wildcard ? rule.slice(2) : rule);
    const labels = [...(wildcard ? ['*'] : []), ...ascii.split('.')];
    // The list only puts a wildcard leftmost, which the matcher relies on.
    if (!ascii || labels.slice(1).some((label) => label === '*' || !LABEL.test(label))) {
      throw new Error(`Bad rule: ${line}`);
    }
    rules.push({ labels, exception, section });
  }
  if (!rules.some((r) => r.section === 'icann') || !rules.some((r) => r.section === 'private')) {
    throw new Error('Expected both the ICANN and the PRIVATE section');
  }
  return rules;
}

/** One serialized subtree per top-level domain, sorted. */
function serialize(rules) {
  const root = new Map();
  for (const { labels, exception } of rules) {
    let children = root;
    let node = null;
    for (const label of [...labels].reverse()) {
      if (!children.has(label)) children.set(label, { rule: null, children: new Map() });
      node = children.get(label);
      children = node.children;
    }
    // An exception wins if a rule is also listed for the same name.
    if (node.rule !== 'exception') node.rule = exception ? 'exception' : 'rule';
  }
  const write = (label, node) => {
    const marker = node.rule === 'exception' ? '!' : node.rule === 'rule' ? '' : '?';
    const kids = [...node.children.keys()].sort();
    const body = kids.length
      ? `(${kids.map((kid) => write(kid, node.children.get(kid))).join(',')})`
      : '';
    return label + marker + body;
  };
  return [...root.keys()].sort().map((tld) => write(tld, root.get(tld)));
}

function header(text, sha256, rules) {
  const field = (name) => (new RegExp(`^// ${name}: (.+)$`, 'm').exec(text) || [])[1] || 'unknown';
  const count = (section) => rules.filter((r) => r.section === section).length;
  return [
    '// Generated by scripts/update-public-suffix-list.js. Do not edit by hand.',
    '//',
    `// Source:  ${SOURCE_URL}`,
    `// Version: ${field('VERSION')}`,
    `// Commit:  ${field('COMMIT')}`,
    `// SHA-256: ${sha256}`,
    `// Rules:   ${count('icann')} ICANN, ${count('private')} private`,
    '//',
    '// The Public Suffix List is subject to the Mozilla Public License, v. 2.0;',
    '// see https://mozilla.org/MPL/2.0/. The trie format is described in the',
    '// script; createSuffixMatcher() in domain.ts reads it.',
  ].join('\n');
}

function render(text) {
  const rules = parseList(text);
  const sha256 = crypto.createHash('sha256').update(text).digest('hex');
  const entries = serialize(rules)
    .map((entry) => `  '${entry}',`)
    .join('\n');
  return `${header(text, sha256, rules)}\n\nexport const PUBLIC_SUFFIX_TRIE: readonly string[] = [\n${entries}\n];\n`;
}

async function main() {
  const fromIndex = process.argv.indexOf('--from');
  let text;
  if (fromIndex >= 0) {
    text = fs.readFileSync(process.argv[fromIndex + 1], 'utf8');
  } else {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error(`${SOURCE_URL}: HTTP ${response.status}`);
    text = await response.text();
  }
  fs.writeFileSync(OUTPUT, render(text));
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}

module.exports = { parseList, serialize, render };
