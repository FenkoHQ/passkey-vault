const translations: Record<ResolvedLanguage, TranslationMap> = { en, ru, zh_CN, ar, fa, es, fr };
let currentLanguage: ResolvedLanguage = 'en';

export function resolveLanguage(language: string | undefined | null): ResolvedLanguage {
  const normalized = (language || '').replace('-', '_');
  if (normalized === 'zh' || normalized.toLowerCase().startsWith('zh_')) return 'zh_CN';
  if (normalized.startsWith('ru')) return 'ru';
  if (normalized.startsWith('ar')) return 'ar';
  if (normalized.startsWith('fa') || normalized.startsWith('fa_IR')) return 'fa';
  if (normalized.startsWith('es')) return 'es';
  if (normalized.startsWith('fr')) return 'fr';
  return 'en';
}

export function getCurrentLanguage(): ResolvedLanguage {
  return currentLanguage;
}

export function isRtlLanguage(language: string): boolean {
  return language === 'ar' || language === 'fa';
}

export async function getStoredLanguage(): Promise<SupportedLanguage> {
  const result = await chrome.storage.local.get(LANGUAGE_STORAGE_KEY);
  const stored = result[LANGUAGE_STORAGE_KEY] as SupportedLanguage | undefined;
  return stored || 'auto';
}

export async function setStoredLanguage(language: SupportedLanguage): Promise<void> {
  await chrome.storage.local.set({ [LANGUAGE_STORAGE_KEY]: language });
}

export async function initI18n(): Promise<ResolvedLanguage> {
  const stored = await getStoredLanguage();
  currentLanguage =
    stored === 'auto' ? resolveLanguage(navigator.language) : resolveLanguage(stored);
  document.documentElement.lang = currentLanguage.replace('_', '-');
  document.documentElement.dir = isRtlLanguage(currentLanguage) ? 'rtl' : 'ltr';
  return currentLanguage;
}

export function t(key: string, params: TranslationParams = {}): string {
  const template = translations[currentLanguage]?.[key] || en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, paramKey: string) => String(params[paramKey] ?? ''));
}

export function pluralKey(baseKey: string, count: number): string {
  return count === 1 ? `${baseKey}_one` : `${baseKey}_other`;
}

export function formatCount(baseKey: string, count: number): string {
  return t(pluralKey(baseKey, count), { count });
}

export function localizePage(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n || '');
  });

  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml || '');
  });

  root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder || '';
    if ('placeholder' in el) {
      (el as HTMLInputElement | HTMLTextAreaElement).placeholder = t(key);
    }
  });

  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle || '');
  });

  const titleKey = document.body?.dataset.i18nTitle;
  if (titleKey) {
    document.title = t(titleKey);
  }
}

export async function initAndLocalize(root: ParentNode = document): Promise<ResolvedLanguage> {
  const language = await initI18n();
  localizePage(root);
  return language;
}
